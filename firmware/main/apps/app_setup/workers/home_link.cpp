#include <fmt/format.h>

using namespace smooth_ui_toolkit::lvgl_cpp;
using namespace setup_workers;

static std::string _tag = "Setup-HomeLink";

HomeLinkWorker::HomeLinkWorker()
{
    _panel = std::make_unique<Container>(lv_screen_active());
    _panel->setBgColor(lv_color_hex(0xFFFFFF));
    _panel->align(LV_ALIGN_CENTER, 0, 0);
    _panel->setBorderWidth(0);
    _panel->setSize(320, 240);
    _panel->setRadius(0);

    _title = std::make_unique<Label>(*_panel);
    _title->setTextFont(&lv_font_montserrat_20);
    _title->setTextColor(lv_color_hex(0x26206A));
    _title->align(LV_ALIGN_TOP_MID, 0, 8);
    _title->setText("HOME LINK");

    _address = std::make_unique<Label>(*_panel);
    _address->setTextFont(&lv_font_montserrat_16);
    _address->setTextColor(lv_color_hex(0x26206A));
    _address->align(LV_ALIGN_TOP_LEFT, 12, 40);

    _token = std::make_unique<Label>(*_panel);
    _token->setTextFont(&lv_font_montserrat_16);
    _token->setTextColor(lv_color_hex(0x0E2F3D));
    _token->align(LV_ALIGN_TOP_LEFT, 12, 66);

    _state = std::make_unique<Label>(*_panel);
    _state->setTextFont(&lv_font_montserrat_14);
    _state->setTextColor(lv_color_hex(0x7E7B9C));
    _state->align(LV_ALIGN_TOP_LEFT, 12, 118);

    _btn_regenerate = std::make_unique<Button>(*_panel);
    apply_button_common_style(*_btn_regenerate);
    _btn_regenerate->setSize(146, 46);
    _btn_regenerate->align(LV_ALIGN_BOTTOM_LEFT, 10, -62);
    _btn_regenerate->label().setText("New Token");
    _btn_regenerate->label().setTextFont(&lv_font_montserrat_16);
    _btn_regenerate->onClick().connect([this]() { _regenerate_clicked = true; });

    _btn_toggle = std::make_unique<Button>(*_panel);
    apply_button_common_style(*_btn_toggle);
    _btn_toggle->setSize(146, 46);
    _btn_toggle->align(LV_ALIGN_BOTTOM_RIGHT, -10, -62);
    _btn_toggle->label().setTextFont(&lv_font_montserrat_16);
    _btn_toggle->onClick().connect([this]() { _toggle_clicked = true; });

    _btn_back = std::make_unique<Button>(*_panel);
    apply_button_common_style(*_btn_back);
    _btn_back->setSize(300, 46);
    _btn_back->align(LV_ALIGN_BOTTOM_MID, 0, -8);
    _btn_back->label().setText("Back");
    _btn_back->label().setTextFont(&lv_font_montserrat_16);
    _btn_back->onClick().connect([this]() { _is_done = true; });

    refresh();
}

void HomeLinkWorker::refresh()
{
    auto info = GetHAL().getHomeLinkInfo();
    _address->setText(fmt::format("Address:  {}:{}", info.ip.empty() ? "(no Wi-Fi)" : info.ip, info.port).c_str());
    std::string shown = "Token:\n";
    for (size_t i = 0; i < info.token.size(); i += 8) {
        shown += info.token.substr(i, 8);
        shown += (i + 8 < info.token.size()) ? ((i / 8) % 2 == 1 ? "\n" : "  ") : "";
    }
    _token->setText(shown.c_str());
    _state->setText(info.enabled ? (info.running ? "Enabled, server running" : "Enabled, waiting for Wi-Fi")
                                 : "Disabled");
    _btn_toggle->label().setText(info.enabled ? "Disable" : "Enable");
    _enabled = info.enabled;
}

void HomeLinkWorker::update()
{
    if (_regenerate_clicked) {
        _regenerate_clicked = false;
        if (!_regenerate_armed) {
            _regenerate_armed = true;
            view::pop_a_toast("Tap New Token again to confirm", view::ToastType::Info, 2500);
            return;
        }
        _regenerate_armed = false;
        GetHAL().regenerateHomeLinkToken();
        mclog::tagInfo(_tag, "token regenerated by user");
        view::pop_a_toast("Token regenerated", view::ToastType::Info, 1600);
        refresh();
    }
    if (_toggle_clicked) {
        _toggle_clicked = false;
        GetHAL().setHomeLinkEnabled(!_enabled);
        mclog::tagInfo(_tag, "home link {}", !_enabled ? "enabled" : "disabled");
        refresh();
    }
    if (GetHAL().millis() - _last_refresh > 1000) {
        _last_refresh = GetHAL().millis();
        refresh();
    }
}
